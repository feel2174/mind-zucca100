// Deterministic random generation based on date and sign ID
export function getDailyFortune(signId: string, dateString: string) {
    // Create a stable hash from signId and dateString
    let hash = 0;
    const str = `${signId}-${dateString}`;
    for (let i = 0; i < str.length; i++) {
        const char = str.charCodeAt(i);
        hash = ((hash << 5) - hash) + char;
        hash = hash & hash; // Convert to 32bit integer
    }
    
    // Convert negative hash to positive
    const absHash = Math.abs(hash);

    // Pick fortunes based on hash
    const general = generalFortunes[absHash % generalFortunes.length];
    const wealth = wealthFortunes[(absHash >> 1) % wealthFortunes.length];
    const love = loveFortunes[(absHash >> 2) % loveFortunes.length];
    const color = colors[(absHash >> 3) % colors.length];

    // Generate 3 lucky numbers from 1 to 45
    const num1 = (absHash % 45) + 1;
    const num2 = ((absHash >> 4) % 45) + 1;
    const num3 = ((absHash >> 5) % 45) + 1;
    
    // Ensure numbers are unique and sorted
    const luckySet = new Set([num1]);
    let attempt = 1;
    while(luckySet.size < 3) {
        luckySet.add(((absHash + attempt) % 45) + 1);
        attempt++;
    }
    const luckyNumbers = Array.from(luckySet).sort((a, b) => a - b);

    return { general, wealth, love, luckyNumbers, color };
}
